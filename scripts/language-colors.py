#!/usr/bin/env python3
# scripts/language-colors.py
"""Write web/app/generated/languageColors.ts from a pinned GitHub Linguist release."""

from pathlib import Path
import json
import sys
import urllib.request

import yaml

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "web/app/generated/languageColors.ts"
RELEASE = "v9.7.0"
SOURCE = f"https://raw.githubusercontent.com/github-linguist/linguist/{RELEASE}/lib/linguist/languages.yml"


def main() -> int:
    with urllib.request.urlopen(SOURCE, timeout=30) as resp:
        languages = yaml.safe_load(resp.read())
    colors = {name: spec["color"].lower() for name, spec in sorted(languages.items()) if spec.get("color")}
    lines = [
        "// web/app/generated/languageColors.ts",
        f"// Generated by scripts/language-colors.py from GitHub Linguist {RELEASE} (MIT licence). Do not edit.",
        "// Keyed by the language name GitHub reports for a repository.",
        "export const LANGUAGE_COLORS: Readonly<Record<string, string>> = {",
    ]
    lines += [f"  {json.dumps(name)}: '{color}'," for name, color in colors.items()]
    lines += ["}", ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(colors)} colours to {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
